"""Emit a chained local job pack (configs + launchers + README)."""

from __future__ import annotations

import json
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

from .family import Family
from .potential import PotentialRef, ResolvedPotential, resolve_potential, write_lockfile
from .stages.base import StageConfig, StageContext
from .stages.metropolis import MetropolisStage
from .stages.sia import SiaStage
from .stages.sqs import SqsStage
from .stages.vacancy import VacancyStage


@dataclass
class PackRequest:
    """What the GUI / CLI asks to write under one pack root."""

    family: Family
    pack_dir: Path
    pot_dir: Optional[Path] = None
    potential: Optional[ResolvedPotential] = None
    lmp: str = "lmp"
    mpirun: str = "mpirun"
    include_sqs: bool = True
    include_metropolis: bool = True
    include_vacancy: bool = True
    include_sia: bool = True
    sqs_params: dict[str, Any] = field(default_factory=dict)
    metro_params: dict[str, Any] = field(default_factory=dict)
    vacancy_params: dict[str, Any] = field(default_factory=dict)
    sia_params: dict[str, Any] = field(default_factory=dict)


@dataclass
class PackResult:
    pack_dir: Path
    stage_dirs: dict[str, Path]
    potential: Optional[ResolvedPotential]
    readme: Path


def _resolve_pot(req: PackRequest) -> Optional[ResolvedPotential]:
    if req.potential is not None:
        return req.potential
    if req.pot_dir is None:
        return None
    return resolve_potential(PotentialRef(pot_dir=Path(req.pot_dir), family_name=req.family.name))


def write_pack_readme(pack_dir: Path, req: PackRequest, stage_dirs: dict[str, Path]) -> Path:
    lines = [
        f"# RCCA job pack — {req.family.name}",
        "",
        "Generated by `rcca_workflow` / Streamlit GUI.",
        "",
        "## Composition",
        "",
        "```json",
        json.dumps(req.family.to_dict(), indent=2),
        "```",
        "",
        "## Stages in this pack",
        "",
    ]
    for name, path in stage_dirs.items():
        lines.append(f"- `{name}/` → `{path.relative_to(pack_dir).as_posix()}`")
    lines += [
        "",
        "## How to run on a cluster",
        "",
        "1. Activate an environment with `icet` (Stage 1), ASE, and a LAMMPS binary that has `tabgap` + `atom/swap`.",
        "2. Set `POT_DIR` to a directory with exactly one `.tabgap` and one `.eam.fs` (or use the paths already in each `manifest.json`).",
        "3. Run stages in order:",
        "",
    ]
    if "sqs" in stage_dirs:
        lines.append("```bash")
        lines.append(f"cd {stage_dirs['sqs'].name}")
        lines.append("python run_sqs.py")
        lines.append("```")
        lines.append("")
    if "metropolis" in stage_dirs:
        lines.append("```bash")
        lines.append(f"cd ../{stage_dirs['metropolis'].name}   # or absolute path")
        lines.append("# ensure poscar_in / Stage-1 poscar_out is available")
        lines.append("python run_metropolis.py")
        lines.append("```")
        lines.append("")
    if "vacancy" in stage_dirs:
        lines.append("```bash")
        lines.append(f"cd ../{stage_dirs['vacancy'].name}")
        lines.append("python run_vacancy.py")
        lines.append("```")
        lines.append("")
    if "sia" in stage_dirs:
        lines.append("```bash")
        lines.append(f"cd ../{stage_dirs['sia'].name}")
        lines.append("python run_sia.py")
        lines.append("```")
        lines.append("")
        lines.append(
            "SIA labels **element pairs only** (e.g. Cr-V). "
            "Geometry / orientation classification is not included."
        )
        lines.append("")
    lines += [
        "## Chain artifacts",
        "",
        "- Stage 1 → `poscar_out`",
        "- Stage 2 → `aged.data`",
        "- Stage 3-1 → `v_form_e.csv`",
        "- Stage 3-2 → `sia_formation_energies_<T>K.csv` + `sia_pairs_<T>K.csv`",
        "",
    ]
    path = pack_dir / "README.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def emit_pack(req: PackRequest) -> PackResult:
    """Write stage folders under ``req.pack_dir`` with manifests and launchers."""
    pack_dir = Path(req.pack_dir).resolve()
    pack_dir.mkdir(parents=True, exist_ok=True)

    pot = _resolve_pot(req)
    needs_pot = req.include_metropolis or req.include_vacancy or req.include_sia
    if needs_pot and pot is None:
        raise ValueError("POT_DIR / resolved potential required for Metropolis / Vacancy / SIA")

    if pot is not None:
        write_lockfile(pot, pack_dir / "potential.lock.json")

    (pack_dir / "family.json").write_text(
        json.dumps(req.family.to_dict(), indent=2) + "\n", encoding="utf-8"
    )

    stage_dirs: dict[str, Path] = {}
    ctx = StageContext(family=req.family, potential=pot, lmp=req.lmp, mpirun=req.mpirun)

    sqs_dir = pack_dir / "01_sqs"
    metro_dir = pack_dir / "02_metropolis"
    vac_dir = pack_dir / "03_vacancy"
    sia_dir = pack_dir / "03_sia"

    if req.include_sqs:
        SqsStage().emit(ctx, StageConfig(work_dir=sqs_dir, params=dict(req.sqs_params)))
        stage_dirs["sqs"] = sqs_dir
        ctx = StageContext(
            family=req.family,
            potential=pot,
            lmp=req.lmp,
            mpirun=req.mpirun,
            prev_dir=sqs_dir,
        )

    if req.include_metropolis:
        MetropolisStage().emit(
            ctx, StageConfig(work_dir=metro_dir, params=dict(req.metro_params))
        )
        stage_dirs["metropolis"] = metro_dir
        ctx = StageContext(
            family=req.family,
            potential=pot,
            lmp=req.lmp,
            mpirun=req.mpirun,
            prev_dir=metro_dir,
        )

    if req.include_vacancy:
        VacancyStage().emit(
            ctx, StageConfig(work_dir=vac_dir, params=dict(req.vacancy_params))
        )
        stage_dirs["vacancy"] = vac_dir

    if req.include_sia:
        # SIA also chains from Metropolis aged.data
        sia_ctx = StageContext(
            family=req.family,
            potential=pot,
            lmp=req.lmp,
            mpirun=req.mpirun,
            prev_dir=metro_dir if req.include_metropolis else ctx.prev_dir,
        )
        SiaStage().emit(sia_ctx, StageConfig(work_dir=sia_dir, params=dict(req.sia_params)))
        stage_dirs["sia"] = sia_dir

    readme = write_pack_readme(pack_dir, req, stage_dirs)
    (pack_dir / "pack.json").write_text(
        json.dumps(
            {
                "family": req.family.name,
                "stages": {k: str(v.name) for k, v in stage_dirs.items()},
                "lmp": req.lmp,
                "mpirun": req.mpirun,
                "pot_dir": str(pot.pot_dir) if pot else None,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return PackResult(pack_dir=pack_dir, stage_dirs=stage_dirs, potential=pot, readme=readme)


def zip_pack(pack_dir: Path, zip_path: Optional[Path] = None) -> Path:
    pack_dir = Path(pack_dir).resolve()
    if zip_path is None:
        zip_path = pack_dir.with_suffix(".zip")
    zip_path = Path(zip_path)
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path in pack_dir.rglob("*"):
            if path.is_file():
                zf.write(path, path.relative_to(pack_dir.parent).as_posix())
    return zip_path
